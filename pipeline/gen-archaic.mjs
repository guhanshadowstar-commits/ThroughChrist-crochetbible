// Generates core/archaic.gen.mjs: old-English verb forms -> modern base word
// ("loveth" -> "love", "believeth" -> "believe", "sayest" -> "say").
//
// Why: KJV/ASV/YLT/Darby/Webster/Geneva are full of -eth/-est forms, so a search for "believe"
// would otherwise miss "whosoever believeth". The map is derived from the corpus itself and
// guarded: a word is only folded if it never appears in the modern texts (WEB + BSB) and its
// base word does. That keeps "earnest", "forest", "priest", "death" and "breath" untouched.
//   node pipeline/gen-archaic.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { VERSIONS } from './versions.mjs';
import { parseVpl } from './vpl.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokens = (id) => {
  const v = VERSIONS.find((x) => x.id === id);
  const file = path.join(ROOT, 'data', 'raw', v.source, `${v.source}_vpl.txt`);
  const counts = new Map();
  for (const { text } of parseVpl(file, { stripMarkup: true }).rows) {
    for (const w of text.toLowerCase().split(/[^\p{L}]+/u)) if (w) counts.set(w, (counts.get(w) ?? 0) + 1);
  }
  return counts;
};

const modern = new Map();
for (const id of ['en-web', 'en-bsb']) for (const [w, n] of tokens(id)) modern.set(w, (modern.get(w) ?? 0) + n);

const archaic = new Map();
for (const id of ['en-kjv', 'en-asv', 'en-ylt', 'en-dby', 'en-wbt', 'en-gnv']) {
  for (const [w, n] of tokens(id)) archaic.set(w, (archaic.get(w) ?? 0) + n);
}

const IRREGULAR = {
  hath: 'have', hast: 'have', hadst: 'had', doth: 'do', dost: 'do', doeth: 'do', doest: 'do',
  saith: 'say', sayeth: 'say', saiest: 'say',
  wilt: 'will', shalt: 'shall', canst: 'can', wast: 'was', didst: 'did',
};

function baseOf(w) {
  if (IRREGULAR[w]) return IRREGULAR[w];
  const ok = (b) => b.length >= 2 && (modern.get(b) ?? 0) >= 3 ? b : null;
  let m;
  // loveth -> love, lovest -> love, useth -> use (the "e" belongs to the verb). Tried first so
  // "useth" becomes "use" and not "us".
  if ((m = /^(.{2,}e)(th|st)$/.exec(w))) {
    const c = ok(m[1]);
    if (c) return c;
  }
  // walketh -> walk, carrieth -> carry, walkest -> walk, sayest -> say
  if ((m = /^(.{2,})(eth|est)$/.exec(w))) {
    const s = m[1];
    const c = ok(s) ?? (s.endsWith('i') ? ok(`${s.slice(0, -1)}y`) : null) ?? ok(`${s}e`);
    if (c) return c;
  }
  return null;
}

// Found by reading the generated list: these fold to the wrong word, so they are left as they are.
const NEVER_FOLD = new Set(['badest', 'marieth', 'thoughtest']);

const map = {};
for (const [w, n] of [...archaic].sort((a, b) => b[1] - a[1])) {
  if (NEVER_FOLD.has(w)) continue;
  if (modern.has(w) && !IRREGULAR[w]) continue; // appears in modern text -> leave alone
  const b = baseOf(w);
  if (b && b !== w) map[w] = b;
}

const out = path.join(ROOT, 'core', 'archaic.gen.mjs');
writeFileSync(out, `// Generated by pipeline/gen-archaic.mjs from the bundled texts. Do not edit.\n// Archaic English verb form -> modern base.\nexport const ARCHAIC_FORMS = ${JSON.stringify(map)};\n`);
console.log(`${Object.keys(map).length} archaic forms written to ${out}`);
const sample = Object.entries(map).slice(0, 40).map(([a, b]) => `${a}>${b}`).join('  ');
