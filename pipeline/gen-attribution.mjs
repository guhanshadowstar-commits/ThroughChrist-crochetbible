// Writes ATTRIBUTION.md from the version registry so credits can never drift from the data.
//   node pipeline/gen-attribution.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { VERSIONS } from './versions.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const section = (lang, title) => [
  `## ${title}`, '',
  ...VERSIONS.filter((v) => v.lang === lang).flatMap((v) => [
    `### ${v.name} (${v.abbr})`,
    `- **License:** ${v.license}`,
    `- **Credit:** ${v.attribution}`,
    `- **Source:** https://ebible.org/${v.source}/`,
    ...(v.notes ? [`- **Notes:** ${v.notes}`] : []),
    '',
  ]),
];

const md = [
  '# Bible texts: licenses and credits',
  '',
  'Generated by `pipeline/gen-attribution.mjs`. Do not edit by hand; edit `pipeline/versions.mjs`.',
  'All texts were obtained from eBible.org in their redistributable form.',
  '',
  'The two Tamil texts are licensed **CC BY-SA 4.0** (share-alike). Wherever the Tamil text is redistributed,',
  'the credit listed below must travel with it and the text must stay under the same license. The Tamil book names',
  'come from the IRV file headers and carry the same license. Application code is separate from the texts.',
  '',
  ...section('en', 'English'),
  ...section('ta', 'Tamil (தமிழ்)'),
  '## Software and artwork',
  '',
  '- **SQLite** (public domain) compiled to WebAssembly by the SQLite team: `@sqlite.org/sqlite-wasm`, Apache-2.0 wrapper.',
  '- **Crochet pictures, sprites and icons** are drawn by this project in code (`core/art/`). Each verse picture is generated from the words of the verse.',
  '',
].join('\n');

writeFileSync(path.join(ROOT, 'ATTRIBUTION.md'), `${md}\n`);
console.log('Wrote ATTRIBUTION.md');
