// Generates docs/FILES.md, the per-file reference: what each file is, how it works, what it uses
// and where it is used. The "uses" and "used by" lists are read from the code itself (imports and
// exports), so they cannot drift; the descriptions come from pipeline/doc-notes.mjs.
//   npm run docs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NOTES } from './doc-notes.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKIP_DIRS = new Set(['node_modules', 'dist', '.git', '.claude', 'data']);
const SKIP_FILES = new Set(['.DS_Store']);

/** Every file that belongs to the project (the same set git tracks), as sorted forward-slash paths. */
export function projectFiles(dir = ROOT, base = '') {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_FILES.has(e.name) || (e.isDirectory() && SKIP_DIRS.has(e.name))) continue;
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...projectFiles(path.join(dir, e.name), rel));
    else out.push(rel);
  }
  return out.sort();
}

const isJs = (f) => /\.(mjs|js)$/.test(f);
const lines = (text) => text.split('\n').length - (text.endsWith('\n') ? 1 : 0);

/** Resolve an import written in file `from` to a project path (or a label for something outside the repo). */
function resolveImport(from, spec) {
  if (spec.startsWith('node:')) return { kind: 'node', label: spec };
  if (!spec.startsWith('.') && !spec.startsWith('/')) return { kind: 'package', label: spec };
  let p = path.posix.normalize(path.posix.join(path.posix.dirname(from), spec));
  // In the served site /js and /core sit side by side; in the repository the app's modules live in web/js.
  if (p.startsWith('web/core/')) p = p.slice(4);
  if (p.startsWith('web/vendor/sqlite/')) return { kind: 'package', label: '@sqlite.org/sqlite-wasm (served from vendor/sqlite)' };
  return { kind: 'file', label: p };
}

function analyse(file, text) {
  const specs = new Set();
  for (const m of text.matchAll(/(?:^|[\s;])(?:import|export)\s+(?:[^'";]*?\s+from\s+)?['"]([^'"]+)['"]/g)) specs.add(m[1]);
  for (const m of text.matchAll(/import\(\s*['"]([^'"]+)['"]\s*\)/g)) specs.add(m[1]);
  const uses = [...specs].map((s) => resolveImport(file, s));
  const exports = new Set();
  for (const m of text.matchAll(/^export\s+(?:async\s+)?(?:const|let|var|function\*?|class)\s+([A-Za-z0-9_$]+)/gm)) exports.add(m[1]);
  for (const m of text.matchAll(/^export\s*\{([^}]+)\}/gm)) m[1].split(',').forEach((n) => exports.add(n.trim().split(/\s+as\s+/).pop()));
  if (/^export\s+default\b/m.test(text)) exports.add('default');
  const tests = isJs(file) && file.endsWith('.test.mjs') ? [...text.matchAll(/^test\(/gm)].length : 0;
  return { uses, exports: [...exports], tests };
}

const link = (f) => (f.includes('/') || f.includes('.') ? `[\`${f}\`](../${f})` : `\`${f}\``);

export function buildFilesDoc() {
  const files = projectFiles();
  const info = new Map();
  for (const f of files) {
    const text = /\.png$/.test(f) ? '' : readFileSync(path.join(ROOT, f), 'utf8');
    const a = isJs(f) ? analyse(f, text) : { uses: [], exports: [], tests: 0 };
    // PNG files have no lines, and FILES.md must not count itself (its own size would change what it prints)
    info.set(f, { lines: /\.png$/.test(f) || f === 'docs/FILES.md' ? 0 : lines(text), ...a });
  }
  const usedBy = new Map(files.map((f) => [f, []]));
  for (const [f, i] of info) for (const u of i.uses) if (u.kind === 'file' && usedBy.has(u.label)) usedBy.get(u.label).push(f);

  const groups = [
    ['Project root', (f) => !f.includes('/') || f.startsWith('.github/')],
    ['docs/: documentation', (f) => f.startsWith('docs/')],
    ['core/: code shared by the build and the app', (f) => f.startsWith('core/') && !f.startsWith('core/art/')],
    ['core/art/: the crochet pictures', (f) => f.startsWith('core/art/')],
    ['pipeline/: build tools and tests (Node only)', (f) => f.startsWith('pipeline/')],
    ['server/: local web server', (f) => f.startsWith('server/')],
    ['web/: the app that runs in the browser', (f) => f.startsWith('web/')],
  ];

  const out = [];
  out.push('# File reference', '',
    'Every file in the project: what it is, how it is done, what it uses and where it is used.', '',
    '*Generated by `npm run docs` (`pipeline/gen-docs.mjs`). The descriptions are written in `pipeline/doc-notes.mjs`; the "Uses", "Used by", "Exports" and line counts are read from the code. Do not edit this file by hand: `pipeline/docs.test.mjs` fails when it is out of date.*', '',
    '**Where code runs:** *Browser* = in the visitor\'s browser; *Node (build)* = on a developer\'s computer or in GitHub Actions while building and testing; *Browser + Node* = the same file is used by both; *Not code* = text, data, images.', '');

  const seen = new Set();
  const toc = [];
  const body = [];
  for (const [title, pick] of groups) {
    const list = files.filter((f) => pick(f) && !seen.has(f));
    if (!list.length) continue;
    list.forEach((f) => seen.add(f));
    toc.push(`- ${title} (${list.length} ${list.length === 1 ? 'file' : 'files'})`);
    body.push(`## ${title}`, '');
    for (const f of list) {
      const n = NOTES[f];
      const i = info.get(f);
      body.push(`### \`${f}\``, '');
      body.push(`**What it is.** ${n.does}`, '');
      if (n.how) body.push(`**How it is done.** ${n.how}`, '');
      body.push(`**Runs in:** ${n.runs}${i.lines ? ` · ${i.lines} lines` : ''}${i.tests ? ` · ${i.tests} tests` : ''}`, '');
      const uses = [
        ...i.uses.filter((u) => u.kind === 'file').map((u) => link(u.label)),
        ...i.uses.filter((u) => u.kind === 'package').map((u) => `\`${u.label}\` (package)`),
        ...i.uses.filter((u) => u.kind === 'node').map((u) => `\`${u.label}\` (built into Node)`),
        ...(n.uses ?? []),
      ];
      if (uses.length) body.push(`**Uses:** ${uses.join(' · ')}`, '');
      const by = [...usedBy.get(f).map(link), ...(n.usedBy ?? [])];
      if (by.length) body.push(`**Used by:** ${by.join(' · ')}`, '');
      if (i.exports.length) body.push(`**Exports:** ${i.exports.map((e) => `\`${e}\``).join(', ')}`, '');
    }
  }
  out.push('## Contents', '', ...toc, '', `${files.length} files in total.`, '', ...body);
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = buildFilesDoc();
  writeFileSync(path.join(ROOT, 'docs', 'FILES.md'), text);
  console.log(`docs/FILES.md written (${text.split('\n').length} lines)`);
}
